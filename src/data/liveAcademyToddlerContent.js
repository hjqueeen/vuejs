const orderLiveAcademyToddlerCards = (cards, sections) => {
  if (!sections?.length) return cards;
  const map = new Map(cards.map((card) => [card.id, card]));
  const ordered = [];
  const seen = new Set();
  for (const section of sections) {
    for (const id of section.cardIds) {
      const card = map.get(id);
      if (card && !seen.has(id)) {
        ordered.push(card);
        seen.add(id);
      }
    }
  }
  for (const card of cards) {
    if (!seen.has(card.id)) ordered.push(card);
  }
  return ordered;
};

export const orderedLiveAcademyToddlerCards = orderLiveAcademyToddlerCards(
  liveAcademyToddlerCards,
  liveAcademyToddlerSections,
);

export const LIVE_ACADEMY_TODDLER_CARD_IDS = orderedLiveAcademyToddlerCards.map((c) => c.id);

export const getLiveAcademyToddlerCardById = (cardId) =>
  liveAcademyToddlerCards.find((c) => c.id === cardId) || null;
